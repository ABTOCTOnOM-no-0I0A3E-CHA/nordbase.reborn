/* Фоновая задача приложения: напоминания о незакрытых заявках.

   Отдельного планировщика на сервере не заводим — лишняя деталь, которую
   придётся чинить после каждого переезда. Приложение и так работает в одном
   экземпляре, поэтому цикл живёт прямо в нём: запустился контейнер — пошли
   напоминания, остановился — некому напоминать, и это честно видно. */

const EVERY_MS = 5 * 60 * 1000;

export async function register() {
  /* Сборка и edge-окружение тоже вызывают register, а база нужна только
     обычному серверному процессу. */
  if (process.env.NEXT_RUNTIME !== 'nodejs') return;

  const { sendPendingReminders } = await import('@/lib/push-reminders');

  const tick = async () => {
    try {
      await sendPendingReminders();
    } catch (cause) {
      console.error('[напоминания] не удалось разослать:', cause);
    }
  };

  /* Первый проход — с задержкой: сразу после старта база может быть ещё не
     поднята, а падать на первом же тике незачем. */
  setTimeout(tick, 30_000);
  setInterval(tick, EVERY_MS);
}
